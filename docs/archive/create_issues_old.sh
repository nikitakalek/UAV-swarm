create_issue "M1-1" "static_voronoi: разбиение области на секторы (Voronoi + CVT)" "module-1" "P1" <<'EOF'
## Цель
Разбить область на N секторов **диаграммой Вороного** с последующим **выравниванием площадей алгоритмом Ллойда (CVT)**.

Почему компактные секторы, а не полосы: при большом N полосы становятся **уже полосы обзора**
и перестают работать (агент перекрывает соседей). Компактные ячейки деградируют плавно, а
суммарная длина границ — а значит и перекрытий — у них минимальна. Теоретически оптимальна
гексагональная решётка (соты); для MVP берём квадратную, гексагональная — опцией.

## Критерий готовности
- [ ] Домен строится как полигон области минус бесполётные зоны
- [ ] Семена ставятся решёткой (квадратная; гексагональная — опция), k = N
- [ ] Ячейки Вороного считаются и обрезаются по домену
- [ ] Выполняется выравнивание площадей алгоритмом Ллойда (CVT), число итераций настраивается
- [ ] Измерен и зафиксирован разброс площадей секторов (max/min)
- [ ] Каждая задача назначена ровно одному сектору (по центроиду или максимуму перекрытия)
- [ ] Полнота, отсутствие дублей, детерминизм
- [ ] Работает на N = 5, 10, 20
- [ ] Крайние случаи: агентов больше, чем задач; сектор без задач; бесполётные зоны
- [ ] Назначение проходит через `PlanValidator`

## Интерфейсы
- `allocate(state, tasks) -> Assignment`
- требуется от `World`: `domain_polygon()`, `no_fly_zones()`

## Зависит от
- M2-2
- M2-5

## Заметки
- Решение: **приблизительное** выравнивание площадей (CVT/Ллойд). Точное равенство через
  power diagram — research-надстройка, если разброс окажется неприемлемым.
- Оценка: 1–2 дня.
EOF

