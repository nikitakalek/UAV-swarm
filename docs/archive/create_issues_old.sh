#!/usr/bin/env bash
#
# SwarmCore — массовое создание задач в GitHub Issues.
#
# ЧТО ДЕЛАЕТ
#   1. Создаёт метки (labels), если их нет.
#   2. Создаёт вехи (milestones) P0..P6, если их нет.
#   3. Создаёт все задачи из списка ниже, ПРОПУСКАЯ уже существующие
#      (сравнение по точному заголовку — можно запускать повторно, дублей не будет).
#
# ТРЕБОВАНИЯ
#   brew install gh
#   gh auth login
#
# ЗАПУСК (из корня репозитория)
#   ./scripts/create_issues.sh
#   REPO=nikitakalek/UAV-swarm ./scripts/create_issues.sh   # если репозиторий не определяется
#   DRY_RUN=1 ./scripts/create_issues.sh                    # только показать, ничего не создавать
#
# ПОСЛЕ ЗАПУСКА
#   - назначь исполнителей на доске (в скрипте их нет — мы не знаем имён);
#   - вкладки М1/М2/М3 в Projects отфильтруй по метке: label:module-1 и т.д.
#
set -euo pipefail

DRY_RUN="${DRY_RUN:-0}"

if ! command -v gh >/dev/null 2>&1; then
  echo "Не найден gh (GitHub CLI). Установи: brew install gh && gh auth login" >&2
  exit 1
fi

if [[ -z "${REPO:-}" ]]; then
  if ! REPO="$(gh repo view --json nameWithOwner -q .nameWithOwner 2>/dev/null)"; then
    echo "Не удалось определить репозиторий. Запусти из папки репозитория или укажи REPO=owner/name" >&2
    exit 1
  fi
fi
echo "Репозиторий: $REPO"
[[ "$DRY_RUN" == "1" ]] && echo "Режим DRY_RUN: задачи создаваться не будут."

# --- метки -------------------------------------------------------------------
ensure_label() {
  gh label create "$1" --color "$2" --description "$3" >/dev/null 2>&1 || true
}
ensure_label "module-1"    "1D76DB" "Модуль 1 — алгоритмы роевого управления"
ensure_label "module-2"    "0E8A16" "Модуль 2 — симулятор и среда"
ensure_label "module-3"    "D93F0B" "Модуль 3 — сенсоры и связь"
ensure_label "integration" "5319E7" "Интеграция, метрики, эксперименты"
ensure_label "docs"        "0075CA" "Документация"
ensure_label "bug"         "B60205" "Ошибка"

# --- вехи --------------------------------------------------------------------
ensure_milestone() {
  if ! gh api "repos/$REPO/milestones?state=all" --paginate --jq '.[].title' 2>/dev/null | grep -qxF "$1"; then
    gh api "repos/$REPO/milestones" -f title="$1" >/dev/null 2>&1 || true
  fi
}
for m in P0 P1 P2 P3 P4 P5 P6; do ensure_milestone "$m"; done

# --- существующие заголовки (для идемпотентности) ----------------------------
EXISTING_TITLES="$(gh issue list --repo "$REPO" --state all --limit 2000 --json title --jq '.[].title' 2>/dev/null || true)"

created=0
skipped=0

create_issue() {
  local code="$1" title="$2" labels="$3" milestone="$4"
  local full_title="[$code] $title"

  if [[ -n "$EXISTING_TITLES" ]] && printf '%s\n' "$EXISTING_TITLES" | grep -qxF "$full_title"; then
    echo "= уже есть: $full_title"
    cat >/dev/null   # поглощаем тело задачи
    skipped=$((skipped + 1))
    return 0
  fi

  local body
  body="$(cat)"

  if [[ "$DRY_RUN" == "1" ]]; then
    echo "+ [dry-run] $full_title   | $labels | $milestone"
    created=$((created + 1))
    return 0
  fi

  local args=(--repo "$REPO" --title "$full_title" --body "$body" --label "$labels")
  [[ -n "$milestone" ]] && args+=(--milestone "$milestone")

  if gh issue create "${args[@]}" >/dev/null; then
    echo "+ создан: $full_title"
    created=$((created + 1))
  else
    echo "! ОШИБКА при создании: $full_title" >&2
    return 1
  fi
}

